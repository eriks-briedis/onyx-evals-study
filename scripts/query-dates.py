#!/usr/bin/env python3
"""Does the scenario date survive into the search queries, and what does search bring back?

For every answer in results/rentals-filters-*.json, three kinds of query reach the index:
  tool     the queries the answering model put in its internal_search call (saved in the result)
  rewrite  Onyx's semantic rewrite of the user message (Langfuse, prompt "reformulates")
  keyword  Onyx's keyword expansion (Langfuse, prompt "ONLY provide the keyword queries")

A query carries the date when it names the scenario's year; "full" when it also names the month.
It names a wrong year when it mentions another year from 2017 on (a version year or today's).

Retrieval is measured on top_documents: the share of retrieved chunks whose file is a version in
force on the scenario date (expected_documents) against other versions of the same instrument
(expected_not_cited). Writes results/query-dates.md.
"""
import ast, json, re
from collections import defaultdict
from datetime import date
from pathlib import Path

import study

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / 'results'
OUT = RESULTS / 'query-dates.md'
PROMPTS = {'rewrite': 'reformulates', 'keyword': 'ONLY provide the keyword queries'}


clickhouse = study.clickhouse


def onyx_queries(sessions):
    """session -> {'rewrite': [...], 'keyword': [...]} from the secondary-flow generations."""
    ids = ','.join("'" + s.replace("'", '') + "'" for s in sessions)
    out = defaultdict(lambda: defaultdict(list))
    for kind, marker in PROMPTS.items():
        # events_full holds several rows per generation; one per span_id.
        rows = clickhouse(f"SELECT session_id, any(output) output FROM events_full WHERE type = 'GENERATION' "
                          f"AND session_id IN ({ids}) AND position(input, '{marker}') > 0 "
                          f"GROUP BY session_id, span_id FORMAT JSONEachRow")
        for r in rows:
            try:
                text = json.loads(r['output'])[0]['content']
            except (ValueError, KeyError, IndexError, TypeError):
                text = r['output']
            out[r['session_id']][kind] += [q.strip() for q in text.splitlines() if q.strip()]
    return out


def dated(query, when):
    """'full', 'year', 'wrong year' or 'none'."""
    years = {int(y) for y in re.findall(r'\b(20[1-3]\d)\b', query)}
    if when.year in years:
        return 'full' if when.strftime('%B').lower() in query.lower() or f'{when:%Y-%m}' in query else 'year'
    return 'wrong year' if any(y >= 2017 for y in years) else 'none'


def main():
    runs = {}
    for path in sorted(RESULTS.glob('rentals-filters-*-*.json')):
        cond, arm = path.stem.removeprefix('rentals-filters-').split('-')
        runs[(cond, arm)] = json.loads(path.read_text())['results']['results']
    sessions = [((r.get('response') or {}).get('output') or {}).get('chat_session_id')
                for rows in runs.values() for r in rows]
    onyx = onyx_queries([s for s in sessions if s])

    lines = ['# Does the scenario date reach the search? - vic-rentals', '',
             "Filters: off = Onyx's date step off, every version searched; on = Onyx's stock date filter (no patch); asof = the perfect filter, a document set holding only the versions in force on the scenario date. "
             'Generated by scripts/query-dates.py. Queries: tool = the model\'s internal_search call, '
             'rewrite / keyword = Onyx\'s own query rewrite and keyword expansion. A query is dated when it '
             'names the scenario year (full = year and month); wrong year = names only another year.', '',
             '| filters | model | kind | queries | full date | year only | wrong year | no date |',
             '|---|---|---|---|---|---|---|---|']
    retrieval = ['', '## What came back', '',
                 'Share of retrieved chunks (top_documents) from the version in force on the scenario date, '
                 'from other versions of the same law, and cases where no in-force chunk came back at all.', '',
                 '| filters | model | answers with docs | chunks | in force | other versions | no in-force chunk |',
                 '|---|---|---|---|---|---|---|']
    for (cond, arm), rows in sorted(runs.items(), key=lambda kv: (kv[0][1], kv[0][0])):
        counts = defaultdict(lambda: defaultdict(int))
        chunks = live = stale = answered = missing = 0
        for r in rows:
            out = (r.get('response') or {}).get('output') or {}
            md = r['testCase']['metadata']
            # promptfoo saves the YAML date as {}, so take it from the case id (vr-<question>-<date>).
            when = date.fromisoformat(md['id'][-10:])
            tool = []
            for c in out.get('tool_calls') or []:
                if c.get('tool_name') != 'internal_search':
                    continue
                args = c.get('tool_arguments') or {}
                tool += (ast.literal_eval(args) if isinstance(args, str) else args).get('queries', [])
            for kind, qs in [('tool', tool), *onyx[out.get('chat_session_id')].items()]:
                for q in qs:
                    counts[kind][dated(q, when)] += 1
            docs = [d.get('semantic_identifier') for d in out.get('top_documents') or []]
            if docs:
                answered += 1
                chunks += len(docs)
                live += sum(d in md['expected_documents'] for d in docs)
                stale += sum(d in md['expected_not_cited'] for d in docs)
                missing += not any(d in md['expected_documents'] for d in docs)
        for kind in ('tool', 'rewrite', 'keyword'):
            c = counts[kind]
            n = sum(c.values())
            pct = lambda k: f'{c[k]} ({100 * c[k] / n:.0f}%)' if n else '-'
            lines.append(f'| {cond} | {arm} | {kind} | {n} | {pct("full")} | {pct("year")} | {pct("wrong year")} | {pct("none")} |')
        share = lambda k: f'{k} ({100 * k / chunks:.0f}%)' if chunks else '-'
        retrieval.append(f'| {cond} | {arm} | {answered} | {chunks} | {share(live)} | {share(stale)} | {missing} |')

    OUT.write_text('\n'.join(lines + retrieval) + '\n')
    print('\n'.join(lines + retrieval))


if __name__ == '__main__':
    main()
