#!/usr/bin/env python3
"""The held-out set, stock against fix: results/variants/heldout*/r<N>/rentals-filters-<cond>-<arm>.json.

The 8 held-out questions (10 slots) were written after the version-filter fix was frozen and
run twice on the same container: filters off (stock, the patch dormant) and on (the fix), 3 runs
each. Per setup: each run's gold pass and judge counts, the mean and range; per slot: runs
passed of 3 under each condition. Writes results/heldout-summary.md.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'results/heldout-summary.md'
import study as c  # noqa: E402  (load, ok, GOLD)

FAMILIES = [('heldout', 'dated, 4 slots'), ('heldout-undated', 'undated, 6 slots')]
ARMS, CONDS = ('haiku', 'sonnet', 'luna', 'luna-api', 'qwen'), ('off', 'on')
COLS = [('0 docs', lambda r: r['docs'] == 0)] + [(g, lambda r, g=g: c.ok(r['metrics'], g)) for g in c.GOLD] + [
    ('gold pass', lambda r: c.ok(r['metrics'], 'retrieval') and all(c.ok(r['metrics'], g) for g in c.GOLD))]
PASS = COLS[-1][1]


def runs_of(fam, cond, arm):
    out = {}
    for n in (1, 2, 3):
        rows = c.load(cond, arm, ROOT / 'results/variants' / fam / f'r{n}')
        if rows:
            out[n] = rows
    return out


def cell(runs, fn):
    vals = [sum(1 for r in rows if fn(r)) for rows in runs.values()]
    return f'{sum(vals) / len(vals):.1f} ({min(vals)}-{max(vals)})' if len(vals) > 1 else str(vals[0])


def main():
    lines = ['# Held-out set - stock against the fix', '',
             'Generated by scripts/heldout-summary.py. 8 questions chosen and gold written after the fix was frozen; '
             'stock = Onyx auto filters off (the patch dormant), fix = on. Judge claude-opus-5-5. '
             'Each cell: mean over the runs (min-max).', '']
    all_runs = {}
    for fam, label in FAMILIES:
        lines += [f'## {label}', '', '| filters | model | runs | ' + ' | '.join(k for k, _ in COLS) + ' | median latency s |',
                  '|---|---|---|' + '---|' * (len(COLS) + 1)]
        for arm in ARMS:
            for cond in CONDS:
                runs = runs_of(fam, cond, arm)
                if not runs:
                    continue
                all_runs[(fam, cond, arm)] = runs
                lat = sorted(r['latency'] or 0 for rows in runs.values() for r in rows)
                lines.append(f'| {cond} | {arm} | {len(runs)} | ' + ' | '.join(cell(runs, fn) for _, fn in COLS)
                             + f' | {lat[len(lat) // 2] / 1000:.0f} |')
        lines.append('')
    lines += ['## Both sets together (10 slots)', '', '| model | stock | fix |', '|---|---|---|']
    for arm in ARMS:
        tot = {}
        for cond in CONDS:
            parts = [all_runs.get((fam, cond, arm)) for fam, _ in FAMILIES]
            if not all(parts):
                continue
            per_run = [sum(1 for p in parts for r in p[n] if PASS(r)) for n in (1, 2, 3) if all(n in p for p in parts)]
            tot[cond] = f'{sum(per_run) / len(per_run):.1f} ({min(per_run)}-{max(per_run)})' if per_run else ''
        if tot:
            lines.append(f"| {arm} | {tot.get('off', '')} | {tot.get('on', '')} |")
    lines += ['', '## Per slot: runs passed of 3', '', 'Gold pass; V = version-cited passes of 3.', '',
              '| slot | ' + ' | '.join(f'{arm} {cond}' for arm in ARMS for cond in CONDS
                                       if any((fam, cond, arm) in all_runs for fam, _ in FAMILIES)) + ' |']
    cols = [(arm, cond) for arm in ARMS for cond in CONDS if any((fam, cond, arm) in all_runs for fam, _ in FAMILIES)]
    lines.append('|---|' + '---|' * len(cols))
    slots = []
    for fam, _ in FAMILIES:
        for key, runs in all_runs.items():
            if key[0] == fam:
                for r in next(iter(runs.values())):
                    if r['case'] not in slots:
                        slots.append(r['case'])
    for slot in slots:
        cells = []
        for arm, cond in cols:
            fam = next((f for f, _ in FAMILIES if (f, cond, arm) in all_runs
                        and any(r['case'] == slot for r in next(iter(all_runs[(f, cond, arm)].values())))), None)
            if not fam:
                cells.append('')
                continue
            runs = all_runs[(fam, cond, arm)]
            rows = [r for rr in runs.values() for r in rr if r['case'] == slot]
            cells.append(f"{sum(1 for r in rows if PASS(r))} (V {sum(1 for r in rows if c.ok(r['metrics'], 'version-cited'))})")
        lines.append(f'| {slot} | ' + ' | '.join(cells) + ' |')
    OUT.write_text('\n'.join(lines) + '\n')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
