#!/usr/bin/env python3
"""The passage-oracle arm: each case with the gold's law passages in the message.

An oracle test hands one step its right answer and measures the rest. Here retrieval is the
step: the model gets exactly the passages the gold answer rests on (the case's ground_truth_ref,
cut in full from the corpus text by questions/<ID>/question.yaml), headed with the document, its
Authorised Version number and the location, and no search tool (persona rentals-oracle). What it
still gets wrong is the writing half.

Reads the compiled datasets so the rubrics, metadata and must_contain checks are the ones every
other arm uses, and adds `vars.passages`; promptfooconfig.rentals-oracle.yaml sends
`{{passages}}` then `{{question}}` as the message.

The output quotes the law in full, so it is built locally and not committed (see NOTICE). Needs
the corpus text (scripts/fetch-corpus.py) and the datasets (npm run cases).

  python3 scripts/make-oracle-dataset.py [--all]     # main set, quick cases unless --all -> datasets/vic-rentals-oracle.yaml
  python3 scripts/make-oracle-dataset.py --heldout   # held-out set, dated + undated -> datasets/vic-rentals-heldout-oracle.yaml
"""
import argparse
import sys
from pathlib import PurePosixPath

import yaml

import study

ROOT = study.ROOT
DATASET = ROOT / 'datasets/vic-rentals.yaml'
CASES = ROOT / 'cases/vic-rentals.yaml'
OUT = ROOT / 'datasets/vic-rentals-oracle.yaml'
HELDOUT_DATASETS = [ROOT / 'datasets/vic-rentals-heldout.yaml', ROOT / 'datasets/vic-rentals-heldout-undated.yaml']
HELDOUT_CASES = [ROOT / 'cases/vic-rentals-heldout.yaml', ROOT / 'cases/vic-rentals-heldout-undated.yaml']
HELDOUT_OUT = ROOT / 'datasets/vic-rentals-heldout-oracle.yaml'


def main_set_layout(text):
    """The main set's oracle runs gave each passage line with its leading indentation removed (the
    page layout's margin column stays, as the corpus chunks carry it); the held-out runs gave the
    text exactly as extracted. Kept as run, so a rebuilt dataset is the one the results came from."""
    return '\n'.join(line.lstrip(' ').rstrip() for line in text.splitlines()).strip('\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--all', action='store_true', help='every case, not only the quick subset')
    ap.add_argument('--heldout', action='store_true', help='the held-out set (dated + undated)')
    args = ap.parse_args()
    if args.heldout:
        tests = [t for name in HELDOUT_DATASETS for t in yaml.safe_load(name.read_text())]
        cases = {c['id']: c for name in HELDOUT_CASES for c in yaml.safe_load(name.read_text())}
    else:
        tests = yaml.safe_load(DATASET.read_text())
        cases = {c['id']: c for c in yaml.safe_load(CASES.read_text())}
    titles = {PurePosixPath(f['path']).name: f['title'] for f in study.corpus_files()}
    out, report = [], []
    for t in tests:
        md = t['metadata']
        if not args.heldout and not args.all and not md.get('quick'):
            continue
        law = study.passages(md['question_id'])
        parts = []
        for ref in cases[md['id']]['ground_truth_ref']:
            hits = [p for p in law if p['doc'] == ref['doc'] and p['section'] == ref['location']]
            if len(hits) != 1:
                sys.exit(f"{md['id']}: {len(hits)} passages match {ref['doc']} + {ref['location']!r}")
            text = hits[0]['text'] if args.heldout else main_set_layout(hits[0]['text'])
            parts.append(f"### {titles[ref['doc']]} ({ref['doc']}), {ref['location']}\n\n{text}")
        passages = 'Law passages (the versions in force on the date of the question):\n\n' + '\n\n'.join(parts)
        new = dict(t)
        new['vars'] = {**t['vars'], 'passages': passages}
        new['metadata'] = {**md, 'oracle': 'passages'}
        out.append(new)
        report.append((md['id'], len(parts), len(passages.split())))
    target = HELDOUT_OUT if args.heldout else OUT
    header = (f'# GENERATED by scripts/make-oracle-dataset.py{" --heldout" if args.heldout else ""} from the datasets and\n'
              '# questions/*/question.yaml. Do not edit, do not commit: it quotes the law in full (NOTICE).\n'
              '# The passage-oracle arm: promptfooconfig.rentals-oracle.yaml sends vars.passages before the question.\n')
    target.write_text(header + yaml.safe_dump(out, allow_unicode=True, sort_keys=False, width=100))
    for cid, n, words in report:
        print(f'{cid}: {n} passages, {words} words')
    print(f'{target.relative_to(ROOT)}: {len(out)} tests')


if __name__ == '__main__':
    main()
