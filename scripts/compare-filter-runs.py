#!/usr/bin/env python3
"""Compare the rentals runs with Onyx's inferred search filters on and off.

Reads results/rentals-filters-<on|off>-<arm>.json (written by the promptfoo runs). When
results/regraded/ holds a re-judged copy (promptfooconfig.regrade.yaml), its verdicts replace
the original's for the judges it ran; a re-judge limited by REGRADE_JUDGES leaves the rest. For
every answer, the time filter Onyx inferred for it: the TIME_FILTER_EXTRACTION generation in
Langfuse's ClickHouse, joined on chat_session_id. Writes results/filters-comparison.md.

A case passes when the answer passes the gold rule (must-mention, must-not-say and
version-cited) and retrieval found every expected document.
"""
import json, re, sys
from collections import defaultdict

import study
from study import GOLD, JUDGED, RESULTS, ROOT, load, ok

OUT = RESULTS / 'filters-comparison.md'
ARMS = ['haiku', 'luna', 'qwen']
TIME_PROMPT = 'You scope an internal search to a time filter'
# asof: the perfect-filter arm (promptfooconfig.rentals-asof.yaml), run with Onyx's filter off.
CONDS = ('on', 'off', 'asof')


def time_filters(session_ids):
    """session_id -> the raw time-filter decision ('updated (None, None)' etc.)."""
    if not session_ids:
        return {}
    db = study.env().get('CLICKHOUSE_DATABASE', 'default')
    ids = ','.join("'" + s.replace("'", '') + "'" for s in session_ids)
    out = {}
    for row in study.clickhouse(f"SELECT session_id, output FROM {db}.events_full "
                                f"WHERE type = 'GENERATION' AND session_id IN ({ids}) "
                                f"AND position(input, '{TIME_PROMPT}') > 0 FORMAT JSONEachRow"):
        try:
            text = json.loads(row['output'])[0]['content']
        except (ValueError, KeyError, IndexError, TypeError):
            text = row['output']
        out[row['session_id']] = text.strip()
    return out


def short_filter(decision):
    if decision is None:
        return 'no call'
    m = re.search(r'\(([^,]*),\s*([^)]*)\)', decision)
    if not m or (m.group(1).strip() == 'None' and m.group(2).strip() == 'None'):
        return 'none'
    # The field matters: these files carry a real updated_at but no created_at.
    field = 'created' if decision[:m.start()].strip().lower().startswith('created') else 'updated'
    return f'{field} {m.group(1).strip()} .. {m.group(2).strip()}'


def main():
    runs = {(c, a): load(c, a) for c in CONDS for a in ARMS}
    runs = {k: v for k, v in runs.items() if v is not None}
    if not runs:
        sys.exit('no results/rentals-filters-*.json yet')
    decisions = time_filters([r['session'] for rows in runs.values() for r in rows if r['session']])
    for rows in runs.values():
        for r in rows:
            r['filter'] = short_filter(decisions.get(r['session']))
            r['passed'] = ok(r['metrics'], 'retrieval') and all(ok(r['metrics'], g) for g in GOLD)

    lines = ['# Inferred search filters on vs off - vic-rentals', '',
             "Filters: off = Onyx's date step off, every version searched; on = Onyx's stock date filter (no patch); asof = the perfect filter, a document set holding only the versions in force on the scenario date. "
             f'Generated by scripts/compare-filter-runs.py from {len(runs)} run file(s). One answer per '
             'case per cell (no repeats), so a one-case difference is within noise.', '',
             '## Summary', '',
             '| filters | model | judged | cases | time filter set | 0 docs | Onyx error | retrieval | must-mention | '
             'must-not-say | version-cited | gold pass | judge errors | median latency s |',
             '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|']
    for (cond, arm), rows in sorted(runs.items(), key=lambda kv: (ARMS.index(kv[0][1]), CONDS.index(kv[0][0]))):
        lines.append(summary_row(cond, arm, rows))

    # The perfect-filter arm runs the quick subset, so it is compared on its own cases only.
    same = [(arm, runs[('off', arm)], runs[('asof', arm)]) for arm in ARMS if ('off', arm) in runs and ('asof', arm) in runs]
    if same:
        lines += ['', '## Perfect date filter vs filters off, same cases', '',
                  'asof searches only the versions in force on the scenario date; off searches every version. '
                  'Both with Onyx\'s own date filter off.', '', lines[6], lines[7]]
        for arm, off, asof in same:
            ids = {r['case'] for r in asof}
            lines.append(summary_row('off', arm, [r for r in off if r['case'] in ids]))
            lines.append(summary_row('asof', arm, asof))

    lines += ['', '## Per case', '',
              'Columns: time filter Onyx inferred, documents returned, then R = retrieval, '
              'M = must-mention, N = must-not-say, V = version-cited; capital = pass, lower case = fail, '
              '? = the judge reply could not be parsed. ERR = Onyx returned an error.', '']
    cases = sorted({r['case'] for rows in runs.values() for r in rows})
    header = ['case'] + [f'{a} {c}' for a in ARMS for c in CONDS if (c, a) in runs]
    lines += ['| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)]
    by = defaultdict(dict)
    for (cond, arm), rows in runs.items():
        for r in rows:
            by[r['case']][(cond, arm)] = r
    for case in cases:
        cells = [case.removeprefix('vr-')]
        for a in ARMS:
            for c in CONDS:
                if (c, a) not in runs:
                    continue
                r = by[case].get((c, a))
                if not r:
                    cells.append('-')
                    continue
                marks = ''.join('?' if r['metrics'].get(m, False) is None else k if ok(r['metrics'], m) else k.lower()
                                for k, m in zip('RMNV', ['retrieval'] + GOLD))
                err = ' ERR' if r['error'] else ''
                cells.append(f"{r['filter']}; {r['docs']} docs; {marks}{err}")
        lines.append('| ' + ' | '.join(cells) + ' |')

    OUT.write_text('\n'.join(lines) + '\n')
    print(f'-> {OUT.relative_to(ROOT)}')
    print('\n'.join(lines[:lines.index('## Per case') - 1]))


def summary_row(cond, arm, rows):
    n = len(rows)
    lat = sorted(r['latency'] or 0 for r in rows)[n // 2] / 1000
    count = lambda f: sum(1 for r in rows if f(r))
    return '| ' + ' | '.join([
        cond, arm, JUDGED[(cond, arm)], str(n),
        str(count(lambda r: r['filter'] not in ('none', 'no call'))),
        str(count(lambda r: r['docs'] == 0)),
        str(count(lambda r: bool(r['error']))),
        *(str(count(lambda r, k=k: ok(r['metrics'], k))) for k in ['retrieval'] + GOLD),
        str(count(lambda r: r['passed'])),
        # Only the judges the pass/fail rule uses; the dropped unsupported-claim's old errors don't count.
        str(sum(1 for r in rows for k in GOLD if k in r['metrics'] and r['metrics'][k] is None)), f'{lat:.0f}']) + ' |'


if __name__ == '__main__':
    main()
