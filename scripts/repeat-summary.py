#!/usr/bin/env python3
"""Three runs of every setup: how much do the scores move between runs?

Run 1 is results/rentals-filters-*.json with its re-judge (results/regraded/); runs 2 and 3 are
results/repeats/r2 and r3, judged by claude-opus-5-5 as they ran. Per setup it gives each run's
counts and their mean and range; the perfect-filter comparison uses the quick cases only. Per
case it counts how many of the three runs passed, which separates stable results from flaky
ones. Writes results/repeat-summary.md.
"""
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'results/repeat-summary.md'
import study as c  # noqa: E402  (load, ok, GOLD)

RUNS = {1: ROOT / 'results', 2: ROOT / 'results/repeats/r2', 3: ROOT / 'results/repeats/r3'}
ARMS, CONDS = ('haiku', 'luna', 'qwen'), ('on', 'off', 'asof')
COLS = [('0 docs', lambda r: r['docs'] == 0)] + [(g, lambda r, g=g: c.ok(r['metrics'], g)) for g in c.GOLD] + [
    ('gold pass', lambda r: c.ok(r['metrics'], 'retrieval') and all(c.ok(r['metrics'], g) for g in c.GOLD))]
PASS = COLS[-1][1]


def runs_of(cond, arm, cases=None):
    """run number -> rows, for the runs that exist; restricted to `cases` when given."""
    out = {}
    for n, root in RUNS.items():
        rows = c.load(cond, arm, root)
        if rows is not None:
            out[n] = [r for r in rows if cases is None or r['case'] in cases]
    return out


def cell(values):
    if not values:
        return '-'
    mean = sum(values) / len(values)
    return f'{mean:.1f} ({min(values)}-{max(values)})' if len(values) > 1 else str(values[0])


def table(title, note, setups):
    lines = [f'## {title}', '', note, '', '| filters | model | runs | cases | ' + ' | '.join(n for n, _ in COLS) + ' | per run (gold pass) |',
             '|---|---|---|---|' + '---|' * (len(COLS) + 1)]
    for cond, arm, runs in setups:
        if not runs:
            continue
        cases = {len(rows) for rows in runs.values()}
        counts = {name: [sum(1 for r in rows if f(r)) for rows in runs.values()] for name, f in COLS}
        lines.append(f'| {cond} | {arm} | {len(runs)} | {"/".join(map(str, sorted(cases)))} | '
                     + ' | '.join(cell(counts[n]) for n, _ in COLS) + ' | '
                     + ', '.join(f'r{n}: {sum(PASS(r) for r in rows)}' for n, rows in runs.items()) + ' |')
    return lines


def main():
    quick = {r['case'] for r in (c.load('asof', 'haiku') or [])}
    lines = ['# Repeat runs - vic-rentals', '',
             "Filters: off = Onyx's date step off, every version searched; on = Onyx's stock date filter (no patch); asof = the perfect filter, a document set holding only the versions in force on the scenario date. "
             'Generated by scripts/repeat-summary.py. Each cell: mean over the runs (min-max). '
             'Run 1 re-judged and runs 2-3 judged by claude-opus-5-5.', '']
    lines += table('All setups', 'Every case each setup ran (16; the perfect-filter arm 10).',
                   [(cond, arm, runs_of(cond, arm)) for arm in ARMS for cond in CONDS])
    lines += [''] + table('Perfect date filter vs filters off, same cases',
                          'The 10 quick cases. asof searches only the versions in force on the scenario date.',
                          [(cond, arm, runs_of(cond, arm, quick)) for arm in ARMS for cond in ('off', 'asof')])

    lines += ['', '## Stability per case', '',
              'How many runs passed each case (gold pass). Stable = every run agrees.', '',
              '| filters | model | runs | always pass | always fail | mixed |', '|---|---|---|---|---|---|']
    flaky = []
    for arm in ARMS:
        for cond in CONDS:
            runs = runs_of(cond, arm)
            if len(runs) < 2:
                continue
            by_case = defaultdict(list)
            for rows in runs.values():
                for r in rows:
                    by_case[r['case']].append(PASS(r))
            full = {k: v for k, v in by_case.items() if len(v) == len(runs)}
            yes = sum(all(v) for v in full.values())
            no = sum(not any(v) for v in full.values())
            mixed = [k for k, v in full.items() if any(v) and not all(v)]
            flaky += [f'{cond} {arm} {k}: {sum(full[k])}/{len(full[k])}' for k in sorted(mixed)]
            lines.append(f'| {cond} | {arm} | {len(runs)} | {yes} | {no} | {len(mixed)} |')
    if flaky:
        lines += ['', 'Mixed cases (runs passed / runs):', ''] + [f'- {f}' for f in flaky]
    OUT.write_text('\n'.join(lines) + '\n')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
