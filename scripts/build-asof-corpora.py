#!/usr/bin/env python3
"""Build one document set per scenario date, holding only the law versions in force on it.

The perfect-filter arm (promptfooconfig.rentals-asof.yaml) searches these instead of
vic-rentals-baseline, so retrieval can only return the right version. That is the
"as-of date" filter the temporal legal QA papers apply before search (Prior et al. 2026,
arXiv:2605.23497; Fan et al. 2026, arXiv:2605.25920). The gap between that arm and the
baseline arm splits the version failures into "wrong version retrieved" and "right version
retrieved, wrong rule applied".

Writes corpus/asof-manifest.yaml (the same PDFs, one doc_set per date) and adds
the doc sets to manifest/manifest.json's extra_corpora. Seed each with
    npm run seed -- --corpus vic-rentals-asof-<date>
"""
import copy, json, sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / 'corpus/manifest.yaml'
OUT = ROOT / 'corpus/asof-manifest.yaml'
CASES = ROOT / 'cases/vic-rentals.yaml'
EVAL_MANIFEST = ROOT / 'manifest/manifest.json'
PREFIX = 'vic-rentals-asof-'


class Quoted(str):
    pass


# A bare 088 reads as the integer 88 under YAML 1.2 (the seed's JavaScript parser).
yaml.SafeDumper.add_representer(Quoted, lambda d, v: d.represent_scalar('tag:yaml.org,2002:str', v, style="'"))


def in_force(f, when):
    return str(f['in_force_from']) <= when and (f['in_force_to'] is None or when <= str(f['in_force_to']))


def main():
    base = yaml.safe_load(BASE.read_text())
    dates = sorted({c['id'][-10:] for c in yaml.safe_load(CASES.read_text())})
    files, sets = [], []
    for when in dates:
        name = PREFIX + when
        live = [f for f in base['files'] if in_force(f, when)]
        # One version per instrument, or the set is not a point in time.
        instruments = [f['title'].split(', Authorised')[0] for f in live]
        assert len(instruments) == len(set(instruments)), (when, instruments)
        for f in live:
            g = copy.deepcopy(f)
            g['doc_set'] = name
            g['version'] = Quoted(g['version'])
            # Only the date and the link: these sets were seeded before the in-force tags were added to the
            # baseline manifest, and with one version per instrument there is nothing for the tags to pick.
            g['onyx_metadata'] = {k: g['onyx_metadata'][k] for k in ('doc_updated_at', 'link')}
            files.append(g)
        sets.append(dict(name=name, tree='baseline/',
                         description=f'The versions in force on {when} only: ' + '; '.join(f['title'] for f in live) + '.'))
        print(f'{name}: {", ".join(Path(f["path"]).stem for f in live)}')

    OUT.write_text('# Generated by scripts/build-asof-corpora.py from manifest.yaml. Do not edit by hand.\n'
                   + yaml.safe_dump(dict(version=1, corpus_id=base['corpus_id'] + '-asof', doc_sets=sets, files=files),
                                    sort_keys=False, allow_unicode=True, width=110))

    manifest = json.loads(EVAL_MANIFEST.read_text())
    extra = [c for c in manifest.get('extra_corpora', []) if not c['doc_set'].startswith(PREFIX)]
    extra += [dict(manifest=str(OUT.relative_to(ROOT)), doc_set=s['name'],
                   document_set_description=f'onyx-evals perfect-filter arm: {s["description"]} Managed by npm run seed.')
              for s in sets]
    manifest['extra_corpora'] = extra
    EVAL_MANIFEST.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + '\n')
    print(f'-> {OUT.relative_to(ROOT)}, {len(sets)} doc sets in {EVAL_MANIFEST.relative_to(ROOT)}')


if __name__ == '__main__':
    sys.exit(main())
