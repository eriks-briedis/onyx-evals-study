#!/usr/bin/env python3
"""Per setup, date step and model: how many cases passed, from the published answers alone.

Reads results/answers/<setup>.jsonl (scripts/export-answers.py) and writes results/summary.md.
Each cell is the mean over the runs (min-max) of the number of cases that passed that check in
one run. Gold pass = retrieval found the expected documents and all three judges passed: the
answer covered every "must mention" point, said nothing on the "must not say" list, and named
the documents in the version in force on the question's date.

Needs nothing but this repo:

  python3 scripts/summarise-answers.py
"""
import json
from collections import defaultdict

import study

SRC = study.RESULTS / 'answers'
OUT = study.RESULTS / 'summary.md'
CHECKS = ['must-mention', 'must-not-say', 'version-cited']
MODELS = ['haiku', 'luna', 'luna-api', 'qwen', 'sonnet', 'sol', 'sol-api', 'opus']
STEPS = ['off (every version searched)', "Onyx's stock date filter", 'perfect filter (one document set per date)',
         'version-filter patch']


def cell(values):
    mean = sum(values) / len(values)
    return f'{mean:.1f} ({min(values)}-{max(values)})' if len(values) > 1 else f'{values[0]}'


def main():
    setups = [p.stem for p in sorted(SRC.glob('*.jsonl'))]
    order = ['baseline', 'pick25', 'prompt2', 'sonnet', 'sol', 'opusarm', 'ctx', 'labels', 'oracle', 'datefilter',
             'datefilter-rest', 'latest-dated', 'undated', 'undated-j1', 'heldout', 'heldout-undated', 'heldout-oracle',
             'heldout-pick25', 'heldout-undated-pick25']
    setups.sort(key=lambda s: order.index(s) if s in order else 99)
    lines = ['# Summary: cases passed per run', '',
             'Generated by scripts/summarise-answers.py from results/answers/*.jsonl, so it needs nothing outside this repo. '
             'Each cell: the number of cases that passed in one run, as the mean over the runs (min-max). '
             'Gold pass = retrieval found the expected documents and all three judges passed. '
             'Setups and what changed in each: [setups.md](setups.md).', '']
    for setup in setups:
        rows = [json.loads(line) for line in (SRC / f'{setup}.jsonl').read_text().splitlines()]
        groups = defaultdict(lambda: defaultdict(list))
        for r in rows:
            groups[(r['date_step'], r['model'])][r['run']].append(r)
        lines += [f'## {setup}', '', '| date step | model | runs | cases | ' + ' | '.join(CHECKS) + ' | gold pass |',
                  '|---|---|---|---|' + '---|' * (len(CHECKS) + 1)]
        for (step, model), runs in sorted(groups.items(), key=lambda kv: (
                STEPS.index(kv[0][0]) if kv[0][0] in STEPS else 9, MODELS.index(kv[0][1]) if kv[0][1] in MODELS else 99)):
            per_run = list(runs.values())
            cases = len({r['case'] for rs in per_run for r in rs})
            cols = [cell([sum((r['verdicts'].get(c) or {}).get('pass') is True for r in rs) for rs in per_run]) for c in CHECKS]
            gold = cell([sum(r['gold_pass'] for r in rs) for rs in per_run])
            lines.append(f'| {step} | {model} | {len(per_run)} | {cases} | ' + ' | '.join(cols) + f' | **{gold}** |')
        lines.append('')
    OUT.write_text('\n'.join(lines))
    print(f'-> {OUT.relative_to(study.ROOT)}')


if __name__ == '__main__':
    main()
